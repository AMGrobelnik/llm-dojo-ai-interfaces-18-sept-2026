"""A complete, runnable spec per chart type — ``chart_gen.py --example bar``.

These are the documentation. A model writing a spec copies the nearest
example and swaps the numbers, which is far more reliable than reading a
schema, and every one of these is exercised by the test suite so a
copied example cannot be stale.
"""

from __future__ import annotations

import numpy as np

_HEXBIN_N = 2400


def _latency_trace(n: int = _HEXBIN_N, seed: int = 7) -> tuple[list[float], list[float]]:
    """Prompt length against end-to-end latency, for the ``hexbin`` example.

    The one example that is computed rather than written out. ``hexbin`` is
    only the right chart past a couple of thousand points, so an example
    small enough to paste into this file would demonstrate the wrong tool —
    and inlining the points instead made this module three times its size,
    at one number per line once the formatter had been through it.

    Seeded, because ``--example hexbin`` has to print the same spec every
    time for the same reason every other example is a literal.
    """
    rng = np.random.default_rng(seed)
    # Gamma, so prompt length has the long right tail that real traffic has.
    tokens = rng.gamma(shape=2.0, scale=520.0, size=n)
    # Latency grows with length, and so does its spread — the pattern a
    # density plot shows and a scatter of this size hides.
    latency = 180.0 + 0.42 * tokens + rng.normal(0.0, 60.0 + 0.05 * tokens)
    return [round(v, 1) for v in tokens], [round(v, 1) for v in latency.clip(min=20.0)]


def _samples(spec: str, n: int, seed: int) -> list[float]:
    """A sample big enough for a shape-of-a-distribution chart to show one.

    Same reasoning as ``_latency_trace``: ``hist`` and ``violin`` are chosen
    over a table or a box precisely when the SHAPE matters, so an example of
    a dozen values demonstrates the wrong tool — a histogram of twelve is
    sparse blocks with gaps, and a ten-point violin is a flat-topped blob
    that cannot show the second mode that is the reason to pick a violin.
    """
    rng = np.random.default_rng(seed)
    if spec == "response_tokens":
        # Log-normal: the long right tail real response lengths have.
        return [round(v, 1) for v in rng.lognormal(mean=5.0, sigma=0.45, size=n)]
    if spec == "latency_baseline":
        return [round(v, 2) for v in rng.normal(128.0, 6.5, size=n)]
    if spec == "latency_ours":
        # Bimodal — a cache hit or a cache miss, nothing in between. A box
        # plot of this reports one median and hides the whole finding.
        hit = rng.normal(92.0, 3.0, size=n // 2)
        miss = rng.normal(118.0, 4.0, size=n - n // 2)
        return [round(v, 2) for v in np.concatenate([hit, miss])]
    raise ValueError(f"unknown sample spec {spec!r}")


